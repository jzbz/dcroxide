    /// The handshake watchdog closes a dribbled connection at the
    /// deadline, and disarming stands it down.
    #[test]
    fn handshake_watchdog_fires_and_disarms() {
        use std::io::Read;
        use std::net::{TcpListener, TcpStream};

        // Fired: a reader with no timeout of its own is unblocked when
        // the watchdog shuts the socket down at the deadline.
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind");
        let addr = listener.local_addr().expect("addr");
        let client = TcpStream::connect(addr).expect("connect");
        let (server_sock, _) = listener.accept().expect("accept");
        let now = Instant::now();
        let watchdog = arm_handshake_watchdog(
            server_sock.try_clone().ok(),
            now.checked_add(Duration::from_millis(150))
                .expect("deadline"),
        );
        // On Windows a local shutdown does not abort a blocked recv;
        // the socket timeout is the cross-platform fallback bounding
        // the test, while unix unblocks at the watchdog's deadline.
        server_sock
            .set_read_timeout(Some(Duration::from_secs(3)))
            .expect("read timeout");
        let mut reader = server_sock;
        let started = Instant::now();
        let mut byte = [0u8; 1];
        let outcome = reader.read(&mut byte);
        assert!(
            matches!(outcome, Ok(0) | Err(_)),
            "the watchdog must end the blocked read"
        );
        assert!(
            started.elapsed() < Duration::from_secs(5),
            "fired late: {:?}",
            started.elapsed()
        );
        drop(watchdog);
        drop(client);

        // Disarmed: the socket outlives the deadline.
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind");
        let addr = listener.local_addr().expect("addr");
        let mut client = TcpStream::connect(addr).expect("connect");
        let (server_sock, _) = listener.accept().expect("accept");
        let now = Instant::now();
        let watchdog = arm_handshake_watchdog(
            server_sock.try_clone().ok(),
            now.checked_add(Duration::from_millis(100))
                .expect("deadline"),
        );
        watchdog.disarm();
        std::thread::sleep(Duration::from_millis(250));
        use std::io::Write;
        let mut server_sock = server_sock;
        server_sock
            .write_all(b"ok")
            .expect("a disarmed socket stays open");
        let mut buf = [0u8; 2];
        client.read_exact(&mut buf).expect("read");
        assert_eq!(&buf, b"ok");
    }

    /// The pre-authentication budget is what its name says: a bound on
    /// the OS threads the pre-authentication phase spends, which is two
    /// per connection (the handler and its handshake watchdog), never a
    /// bound on connections that quietly costs twice as much.  It also
    /// scales with the configured cap and keeps a floor, so dcrd's tiny
    /// defaults still get a usable handshake phase.
    #[test]
    fn the_pre_auth_budget_bounds_threads_not_just_connections() {
        for cap in [0usize, 1, 10, 25, 100, 1000, usize::MAX] {
            let (soft, hard) = pre_auth_budget(cap);
            assert!(soft >= 32, "cap {cap}: the floor keeps the phase usable");
            assert!(soft < hard, "cap {cap}: the reserve must be real");
            assert!(
                hard.saturating_mul(THREADS_PER_PRE_AUTH_CONNECTION) <= MAX_PRE_AUTH_THREADS,
                "cap {cap}: {hard} connections at {THREADS_PER_PRE_AUTH_CONNECTION} threads \
                 each exceeds the {MAX_PRE_AUTH_THREADS}-thread ceiling the constant promises"
            );
        }
        // The budget grows with the cap up to the thread roof.
        assert_eq!(pre_auth_budget(0), (32, 64), "dcrd's zero cap");
        assert_eq!(pre_auth_budget(10), (32, 64), "the dcrd default cap");
        assert_eq!(pre_auth_budget(100), (108, 216));
        assert_eq!(
            pre_auth_budget(usize::MAX),
            (128, 256),
            "an absurd cap saturates at the thread roof rather than overflowing"
        );
    }

    /// Eviction passes over a connection that has sent a request head
    /// and takes a stalled one instead, even though the stalled one
    /// arrived later.
    ///
    /// Shedding the arrivals that never send a request is the entire
    /// justification for this tier -- they are the ones costing a thread
    /// for nothing -- and `PARITY.md`'s divergences row states it as the
    /// rule.  Taking the oldest regardless would kill a client that is
    /// being served and answer it nothing, while the stall that caused
    /// the pressure survived.  Reported as RVW-010 by an external review
    /// of `382864f5`, which found the row describing a control the code
    /// did not implement.
    #[test]
    fn eviction_prefers_a_connection_that_has_not_sent_a_request() {
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind");
        let addr = listener.local_addr().expect("addr");
        let gate = Arc::new(PreAuthGate::with_budget(2, 3));

        let open = |gate: &Arc<PreAuthGate>| {
            let client = TcpStream::connect(addr).expect("connect");
            let (server, peer) = listener.accept().expect("accept");
            let slot = gate.admit(server.try_clone().ok(), &peer);
            (client, server, slot)
        };

        // The oldest connection is mid-request: it has sent a head.
        let (mut serving, _serving_server, serving_slot) = open(&gate);
        serving_slot.as_ref().expect("admitted").mark_head_done();
        // A later arrival that has sent nothing.
        let (mut stalled, _stalled_server, _stalled_slot) = open(&gate);
        assert_eq!(gate.live(), 2, "the nominal budget is full");

        let (_third, _third_server, third_slot) = open(&gate);
        assert!(third_slot.is_some(), "the arrival is admitted");

        stalled
            .set_read_timeout(Some(Duration::from_secs(10)))
            .expect("read timeout");
        let mut buf = [0u8; 1];
        assert!(
            matches!(stalled.read(&mut buf), Ok(0)),
            "the stalled connection is the one disconnected, not the older one being served"
        );

        // The connection that had sent a head is untouched.
        serving
            .set_read_timeout(Some(Duration::from_millis(200)))
            .expect("read timeout");
        let mut buf = [0u8; 1];
        assert!(
            serving.read(&mut buf).is_err(),
            "a connection that sent a request head must not be evicted while a stalled one lives"
        );
    }

    /// When every live connection has sent a head there is no stalled
    /// one to prefer, and the tier still has to shed something to stay
    /// under its ceiling, so it falls back to the oldest.
    #[test]
    fn eviction_falls_back_to_the_oldest_when_all_have_sent_a_request() {
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind");
        let addr = listener.local_addr().expect("addr");
        let gate = Arc::new(PreAuthGate::with_budget(2, 3));

        let open = |gate: &Arc<PreAuthGate>| {
            let client = TcpStream::connect(addr).expect("connect");
            let (server, peer) = listener.accept().expect("accept");
            let slot = gate.admit(server.try_clone().ok(), &peer);
            (client, server, slot)
        };

        let (mut oldest, _oldest_server, oldest_slot) = open(&gate);
        oldest_slot.as_ref().expect("admitted").mark_head_done();
        let (_newer, _newer_server, newer_slot) = open(&gate);
        newer_slot.as_ref().expect("admitted").mark_head_done();

        let (_third, _third_server, third_slot) = open(&gate);
        assert!(third_slot.is_some(), "the arrival is admitted");

        oldest
            .set_read_timeout(Some(Duration::from_secs(10)))
            .expect("read timeout");
        let mut buf = [0u8; 1];
        assert!(
            matches!(oldest.read(&mut buf), Ok(0)),
            "with no stalled connection to shed, the oldest goes"
        );
    }

    /// Admitting past the nominal budget disconnects the *oldest*
    /// pre-authentication connection rather than the arriving one: a
    /// stalled flood is exactly the oldest set, so an arriving client
    /// gets in and the flood pays for it.  The evicted entry stays
    /// counted until its handler releases the slot, and past the reserve
    /// admission genuinely fails.
    #[test]
    fn admission_disconnects_the_oldest_pre_auth_connection() {
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind");
        let addr = listener.local_addr().expect("addr");
        let gate = Arc::new(PreAuthGate::with_budget(2, 3));

        // A connected pair, with the server side registered in the gate.
        let open = |gate: &Arc<PreAuthGate>| {
            let client = TcpStream::connect(addr).expect("connect");
            let (server, peer) = listener.accept().expect("accept");
            let slot = gate.admit(server.try_clone().ok(), &peer);
            (client, server, slot)
        };

        let (mut oldest, _oldest_server, oldest_slot) = open(&gate);
        let (newer, newer_server, _newer_slot) = open(&gate);
        assert_eq!(gate.live(), 2, "the nominal budget is full");

        // The third admission is granted and evicts the oldest.
        let (_third, _third_server, third_slot) = open(&gate);
        assert!(
            third_slot.is_some(),
            "an arriving connection must be admitted, not dropped"
        );
        assert_eq!(
            gate.live(),
            3,
            "the evicted entry stays counted until its handler releases it"
        );

        oldest
            .set_read_timeout(Some(Duration::from_secs(10)))
            .expect("read timeout");
        let mut buf = [0u8; 1];
        assert!(
            matches!(oldest.read(&mut buf), Ok(0)),
            "the oldest pre-authentication connection is the one disconnected"
        );

        // The connection after it was left alone: it still carries data.
        let mut newer_server = newer_server;
        newer_server
            .write_all(b"x")
            .expect("the newer socket is open");
        let mut newer = newer;
        newer
            .set_read_timeout(Some(Duration::from_secs(10)))
            .expect("read timeout");
        newer.read_exact(&mut buf).expect("read");
        assert_eq!(&buf, b"x", "only the oldest connection is evicted");

        // Past the reserve, admission fails outright rather than
        // evicting a connection it has no room to replace.
        let (_fourth, _fourth_server, fourth_slot) = open(&gate);
        assert!(
            fourth_slot.is_none(),
            "the reserve is an absolute ceiling, not another eviction round"
        );

        // Releasing the evicted entry's slot frees its capacity.
        drop(oldest_slot);
        assert_eq!(gate.live(), 2, "a released slot leaves the pool");
    }

    /// A slot is released on every exit path, including an unwind, so a
    /// panicking handler cannot permanently consume capacity.
    #[test]
    fn pre_auth_slots_are_released_even_on_unwind() {
        let gate = Arc::new(PreAuthGate::with_budget(3, 3));
        let peer: SocketAddr = "127.0.0.1:1234".parse().expect("addr");

        let held: Vec<PreAuthSlot> = (0..3)
            .map(|_| gate.admit(None, &peer).expect("within the budget"))
            .collect();
        assert_eq!(gate.live(), 3);
        assert!(
            gate.admit(None, &peer).is_none(),
            "the ceiling must refuse rather than over-admit"
        );
        drop(held);
        assert_eq!(gate.live(), 0, "drops release the slots");

        // An unwind through a scope holding a slot still releases it.
        let unwind_gate = Arc::clone(&gate);
        let result = std::panic::catch_unwind(move || {
            let _slot = unwind_gate.admit(None, &peer).expect("admit");
            assert_eq!(unwind_gate.live(), 1);
            panic!("handler blew up");
        });
        assert!(result.is_err(), "the panic must propagate");
        assert_eq!(gate.live(), 0, "a panicking handler must not leak its slot");
    }

    /// The shed lines are rate limited, so an accept flood cannot become
    /// a log flood, and the suppressed count is reported on the next
    /// line — zero in the unflooded case, which keeps dcrd's message
    /// text verbatim.
    #[test]
    fn shed_logging_is_rate_limited_with_a_suppressed_count() {
        let interval = Duration::from_secs(10);
        let start = Instant::now();
        let mut limiter = RateLimitedLog::new();

        assert_eq!(
            limiter.record(interval, start),
            Some(0),
            "the first event logs with nothing suppressed"
        );
        for i in 1..100u32 {
            let at = start
                .checked_add(Duration::from_millis(u64::from(i)))
                .expect("instant");
            assert_eq!(
                limiter.record(interval, at),
                None,
                "a flood inside the interval must not log"
            );
        }
        let after = start.checked_add(interval).expect("instant");
        assert_eq!(
            limiter.record(interval, after),
            Some(99),
            "the next line reports how many were suppressed"
        );
        let later = after.checked_add(interval).expect("instant");
        assert_eq!(
            limiter.record(interval, later),
            Some(0),
            "the counter resets with each emitted line"
        );
    }

    /// The shed line composed for the standard-client cap keeps dcrd's
    /// text verbatim when nothing was suppressed, and carries the
    /// suppressed count when a flood was throttled.
    #[test]
    fn a_throttled_shed_line_carries_its_suppressed_count() {
        let interval = Duration::from_secs(10);
        let start = Instant::now();
        let limiter = Mutex::new(RateLimitedLog::new());
        let message = "Max RPC clients exceeded [10] - disconnecting client 127.0.0.1:5000";

        assert_eq!(
            shed_line(&limiter, message, interval, start).as_deref(),
            Some(message),
            "the unflooded line is dcrd's text, unadorned"
        );
        for i in 1..5u32 {
            let at = start
                .checked_add(Duration::from_millis(u64::from(i)))
                .expect("instant");
            assert_eq!(
                shed_line(&limiter, message, interval, at),
                None,
                "a flood inside the interval must not log"
            );
        }
        let after = start.checked_add(interval).expect("instant");
        assert_eq!(
            shed_line(&limiter, message, interval, after).as_deref(),
            Some(format!("{message} (4 more suppressed)").as_str()),
            "the next line accounts for the events the flood cost"
        );
    }

    /// A connected loopback pair, with the accepted server side first.
    #[cfg(unix)]
    fn loopback_pair() -> (TcpStream, TcpStream) {
        let listener = std::net::TcpListener::bind("127.0.0.1:0").expect("bind loopback");
        let addr = listener.local_addr().expect("local addr");
        let client = TcpStream::connect(addr).expect("connect");
        let (server, _) = listener.accept().expect("accept");
        (server, client)
    }

    /// The case that motivated the whole change: a peer that writes
    /// before closing, which is what every TLS client does because it
    /// sends a `close_notify` record ahead of the FIN.
    ///
    /// The peek cannot see past those bytes, so on its own it reports
    /// the client as still connected and `getwork` keeps holding the
    /// work semaphore for a caller that is gone. `POLLRDHUP` is set by
    /// the FIN regardless of what is queued in front of it.
    ///
    /// Deterministic: the write and the shutdown both complete before
    /// anything is asserted, and both flags are level-triggered, so
    /// there is no window to lose.
    ///
    /// Gated to the platforms that have `POLLRDHUP`, matching
    /// [`peer_half_closed`]. On macOS and Windows this case is the open
    /// half of the PARITY entry, so asserting it there would be
    /// asserting a gap the port does not claim to have closed.
    #[test]
    #[cfg(all(
        unix,
        any(
            target_os = "freebsd",
            target_os = "illumos",
            all(
                any(target_os = "linux", target_os = "android"),
                not(any(target_arch = "sparc", target_arch = "sparc64"))
            )
        )
    ))]
    fn a_hangup_behind_pending_bytes_is_seen() {
        use std::io::Write;
        let (server, mut client) = loopback_pair();

        // A close_notify-shaped prelude, then the FIN.
        client.write_all(b"\x15\x03\x03\x00\x02").expect("write");
        client
            .shutdown(std::net::Shutdown::Write)
            .expect("half-close");
        // Let the loopback deliver both; the assertions below are
        // level-triggered, so this only has to be long enough once.
        std::thread::sleep(Duration::from_millis(50));

        assert!(
            !peeked_eof(&server),
            "the peek must find the pending bytes, not the FIN --              if this fails the test is no longer covering the TLS shape"
        );
        assert_eq!(
            peer_half_closed(&server),
            Some(true),
            "RDHUP must report the half-close that the peek missed"
        );
        assert!(
            client_hung_up(Some(&server)),
            "the combined check must report the client as gone"
        );
    }

    /// The abrupt close that already worked, which must keep working:
    /// a FIN with nothing buffered ahead of it.
    #[test]
    #[cfg(unix)]
    fn a_bare_hangup_is_still_seen() {
        let (server, client) = loopback_pair();
        client
            .shutdown(std::net::Shutdown::Write)
            .expect("half-close");
        std::thread::sleep(Duration::from_millis(50));

        assert!(peeked_eof(&server), "a bare FIN peeks as zero-length");
        assert!(
            client_hung_up(Some(&server)),
            "the combined check still reports the client as gone"
        );
    }

    /// And a live connection is not mistaken for a dead one, with and
    /// without unread data pending -- the pipelined-request case, which
    /// dcrd deliberately does NOT treat as a hangup (`server.go:748-771`
    /// in Go's net/http: a byte arriving is a pipelined request, and
    /// only a read *error* cancels).
    #[test]
    #[cfg(unix)]
    fn a_live_connection_is_not_reported_gone() {
        use std::io::Write;
        let (server, mut client) = loopback_pair();

        assert!(
            !client_hung_up(Some(&server)),
            "an idle live connection is not a hangup"
        );

        client.write_all(b"{\"jsonrpc\":\"1.0\"}").expect("write");
        std::thread::sleep(Duration::from_millis(50));
        assert!(
            !client_hung_up(Some(&server)),
            "a pipelined request is not a hangup"
        );

        // Keep the client alive to here, so nothing above raced a drop.
        drop(client);
    }
