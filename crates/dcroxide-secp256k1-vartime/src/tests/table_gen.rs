//! The generator of `src/g_tables.rs` (test builds only).
//!
//! libsecp256k1's `ecmult_compute_table` (ecmult_compute_table_impl.h:
//! 16-34): entry 0 is the base, d = 2 * base, entry j = entry j-1 + d;
//! the second table repeats it on 2^128 * base, after 128 doublings
//! (:36-47).  The chain stays Jacobian (`gej_add_var`) and is converted
//! with one batch inversion (`ge_set_all_gej_var`) rather than the C's
//! conversion per entry; the result is the same, since the storage form is
//! the normalized affine point.
//!
//! [`table_file`] writes the whole file; the regeneration test
//! (`tables::regenerate`) compares it with the committed one byte for byte.

#![allow(
    clippy::arithmetic_side_effects,
    reason = "test-only generator: window <= 16, indices in range"
)]

use std::fmt::Write as _;

use crate::group::{Ge, GeStorage, Gej};

/// `ecmult_compute_table` (ecmult_compute_table_impl.h:16-34): the
/// 2^(w-2) odd multiples of `base` in storage form.
///
/// # Panics
///
/// If `base` is infinity, if an entry is infinity (a group of order at
/// most 2^(w-1)), or past the inversion's cap.
pub(crate) fn compute_table(window: u32, base: &Gej) -> Vec<GeStorage> {
    assert!(!base.infinity);
    let n = 1usize << (window - 2);
    let d = base.double_var(None);
    let mut chain = Vec::with_capacity(n);
    chain.push(*base);
    for j in 1..n {
        let next = chain[j - 1].add_var(&d, None);
        chain.push(next);
    }
    let mut ge = vec![Ge::INFINITY; n];
    Ge::set_all_gej_var(&mut ge, &chain).expect("inversion cap");
    ge.iter()
        .map(|p| {
            assert!(!p.infinity, "table entry at infinity");
            p.to_storage()
        })
        .collect()
}

/// `ecmult_compute_two_tables` (ecmult_compute_table_impl.h:36-47): the
/// tables of `base` and of 2^128 * `base`.
pub(crate) fn compute_two_tables(window: u32, base: &Ge) -> (Vec<GeStorage>, Vec<GeStorage>) {
    let mut gj = Gej::set_ge(base);
    let t = compute_table(window, &gj);
    for _ in 0..128 {
        gj = gj.double_var(None);
    }
    let t128 = compute_table(window, &gj);
    (t, t128)
}

/// One entry, one line.
fn entry(s: &GeStorage) -> String {
    format!(
        "GeStorage {{ x: [0x{:016x}, 0x{:016x}, 0x{:016x}, 0x{:016x}], y: [0x{:016x}, 0x{:016x}, 0x{:016x}, 0x{:016x}] }},",
        s.x[0], s.x[1], s.x[2], s.x[3], s.y[0], s.y[1], s.y[2], s.y[3]
    )
}

/// The text of `src/g_tables.rs` for secp256k1's G at `window`.
pub(crate) fn table_file(window: u32) -> String {
    let (t, t128) = compute_two_tables(window, &crate::group::G);
    let n = t.len();
    let mut s = String::new();
    for line in [
        "// SPDX-License-Identifier: ISC AND MIT",
        "//",
        "// GENERATED by src/tests/table_gen.rs (test `tables::regenerate`); do not edit.",
        "// The scheme is libsecp256k1's ecmult_compute_table, src/ecmult_compute_table_impl.h",
        "// (Copyright (c) 2013, 2014, 2017, 2021 Pieter Wuille, Andrew Poelstra, Jonas Nick,",
        "// Russell O'Connor), as vendored by secp256k1-sys 0.14.1.  MIT; see NOTICE.",
        "//",
    ] {
        let _ = writeln!(s, "{line}");
    }
    let _ = writeln!(
        s,
        "// Generator: secp256k1's G (SEC2 2.7.1) and 2^128*G.  Window {window}: {n} entries"
    );
    for line in [
        "// per table; entry j is (2j+1)*G, resp. (2j+1)*2^128*G, as the normalized",
        "// affine x and y in little-endian 64-bit limbs.  To regenerate, run",
        "// DCROXIDE_REGEN_TABLES=<dir> cargo test -p dcroxide-secp256k1-vartime tables::regenerate",
        "// and copy <dir>/g_tables.rs here.",
        "//",
        "//! The static tables of G and 2^128*G the Straus loop reads (generated).",
        "",
        "use crate::group::GeStorage;",
        "",
        "/// The window of these tables.",
    ] {
        let _ = writeln!(s, "{line}");
    }
    let _ = writeln!(s, "pub(crate) const WINDOW_G: u32 = {window};");
    for (name, doc, tab) in [
        ("PRE_G", "Odd multiples of G: entry j is (2j+1)*G.", &t),
        (
            "PRE_G_128",
            "Odd multiples of 2^128*G: entry j is (2j+1)*2^128*G.",
            &t128,
        ),
    ] {
        let _ = writeln!(s);
        let _ = writeln!(s, "/// {doc}");
        let _ = writeln!(s, "#[rustfmt::skip]");
        let _ = writeln!(
            s,
            "pub(crate) static {name}: [GeStorage; 1 << (WINDOW_G - 2)] = ["
        );
        for e in tab {
            let _ = writeln!(s, "{}", entry(e));
        }
        let _ = writeln!(s, "];");
    }
    s
}
