//! The 192 constant points of K-wrap's `y+P` stratum.
//!
//! A point with a small y would need a cube root mod P to find, which this
//! crate's arithmetic does not offer (`k256` keeps its field element type
//! private), so the points were computed offline and are checked here with
//! `k256` instead: each is on the curve, and its y is below 2^256 − P, so
//! y + P still fits in 32 bytes.
//!
//! The table holds every point whose y is one of the 32 smallest or the 32
//! largest values below 2^256 − P for which y² − 7 is a cube mod P, three
//! points (three x) per y.  The smallest y are 1, 6, 11 and 13; the largest
//! is 4,294,968,270, so y + P reaches 2^256 − 3.  The second point is the
//! one of dcrd's own "uncompressed y > p (p + 1 -- aka 1)" public key test
//! row.  Each x is four big-endian 64-bit words, most significant first.

/// One K-wrap point: x as big-endian words, and y.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WrapPoint {
    /// x, as four big-endian 64-bit words, most significant first.
    pub x: [u64; 4],
    /// y, below 2^256 − P.
    pub y: u64,
}

impl WrapPoint {
    /// x as 32 big-endian bytes.
    pub fn x_bytes(&self) -> [u8; 32] {
        let mut out = [0u8; 32];
        for (chunk, word) in out.as_chunks_mut::<8>().0.iter_mut().zip(self.x) {
            *chunk = word.to_be_bytes();
        }
        out
    }

    /// y as 32 big-endian bytes.
    pub fn y_bytes(&self) -> [u8; 32] {
        crate::arith::be_from_u64(self.y)
    }
}

const fn p(x: [u64; 4], y: u64) -> WrapPoint {
    WrapPoint { x, y }
}

